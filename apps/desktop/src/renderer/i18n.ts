export function isUiLocale(value: string | null): value is UiLocale {
  return value === 'en' || value === 'ko';
}

export function systemUiLocale(language: string): UiLocale {
  return language.toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

export function uiText(locale: UiLocale, key: UiTextKey, values: UiTextValues = {}): string {
  const resolved: UiTextValues = { app: DEFAULT_APP_NAME, ...values };
  return copy[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = resolved[name];
    return value === undefined ? placeholder : String(value);
  });
}
